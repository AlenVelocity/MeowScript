// `meowscript packages --json` -> src/generated/stdlib.ts. Keeps the committed file when cargo
// is not available.

import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("../../", import.meta.url));
const outFile = fileURLToPath(new URL("../src/generated/stdlib.ts", import.meta.url));

const result = spawnSync("cargo", ["run", "--quiet", "-p", "meowscript-cli", "--", "packages", "--json"], {
  cwd: repoRoot,
  encoding: "utf8",
});

if (result.error || result.status !== 0) {
  const reason = result.error ? result.error.message : (result.stderr || "").trim().split("\n").pop();
  console.log(`sync-stdlib: cargo not usable (${reason}), keeping the committed src/generated/stdlib.ts`);
  process.exit(0);
}

const listing = JSON.parse(result.stdout);

const header = `// Generated by scripts/sync-stdlib.mjs from \`meowscript packages --json\`. Do not edit by hand.

export interface BuiltinDoc {
  name: string;
  arity: string;
  doc: string;
}

export interface ConstantDoc {
  name: string;
  /** A number, or "Infinity" for values JSON can't carry. */
  value: number | string;
}

export interface PackageDoc {
  name: string;
  doc: string;
  functions: BuiltinDoc[];
  constants: ConstantDoc[];
}

export interface StdlibDoc {
  version: string;
  prelude: BuiltinDoc[];
  packages: PackageDoc[];
}

export const stdlib: StdlibDoc = `;

writeFileSync(outFile, `${header}${JSON.stringify(listing, null, 2)};\n`);
console.log(`sync-stdlib: wrote ${listing.packages.length} packages for MeowScript ${listing.version}`);
