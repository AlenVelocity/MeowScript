// examples/*.meow -> src/generated/examples.ts. Keeps the committed file when examples/ is
// not around (on Vercel, say).

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ORDER = ["hello", "yarn", "fizzbuzz", "closures", "recursion", "furrball", "whiskers", "curious", "toy", "naptime"];

const examplesDir = new URL("../../examples/", import.meta.url);
const outFile = fileURLToPath(new URL("../src/generated/examples.ts", import.meta.url));

if (!existsSync(examplesDir)) {
  console.log("sync-examples: examples/ not found, keeping the committed src/generated/examples.ts");
  process.exit(0);
}

const examples = ORDER.map((id) => {
  const raw = readFileSync(new URL(`${id}.meow`, examplesDir), "utf8").replace(/\r\n/g, "\n");
  const lines = raw.split("\n").filter((line) => !line.includes("// test: skip"));
  const descriptionLine = lines.find((line) => line.startsWith("//"));
  const description = descriptionLine ? descriptionLine.replace(/^\/\/\s*/, "") : "";
  const source = lines.join("\n").replace(/^\n+/, "").replace(/\n+$/, "\n");
  return { id, file: `${id}.meow`, description, source };
});

const header = `// Generated by scripts/sync-examples.mjs from examples/*.meow. Do not edit by hand.

export interface Example {
  id: string;
  file: string;
  description: string;
  source: string;
}

export const examples: Example[] = `;

writeFileSync(outFile, `${header}${JSON.stringify(examples, null, 2)};\n`);
console.log(`sync-examples: wrote ${examples.length} examples`);
